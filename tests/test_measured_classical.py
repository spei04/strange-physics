@pytest.mark.parametrize("outcome", ["fit", "preparation", "unscorable", "evaluator"])
def test_measured_classical_scientific_outcomes_remain_distinct(
    outcome: str,
    tmp_path: Path,
    actual_build: TrustedInstallation,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    experiment_case: Literal["regular", "stationary", "overlap"] = (
        "stationary" if outcome == "fit" else "overlap" if outcome == "preparation" else "regular"
    )
    f, _, _, candidate = candidate_fixture(
        tmp_path / outcome, actual_build, experiment_case=experiment_case
    )
    request = classical_request(f, raw(candidate.receipt), candidate.result)

    def arithmetic(*args: Any, **kwargs: Any) -> Any:
        raise ArithmeticError("finite scientific arithmetic fault")

    if outcome == "unscorable":
        monkeypatch.setattr(prediction_producer, "_state_at_time", arithmetic)
    elif outcome == "evaluator":
        monkeypatch.setattr(evaluation_producer, "_reference_probe", arithmetic)
    value = commit_journal_classical(f.root, request)
    p = value.result.payload
    assert p.fit is not None and len(p.fit.observations.records) == 12
    assert p.fit.observations.records[-1].status == "failed"
    if outcome in {"fit", "preparation"}:
        assert p.status == ("fit_failed" if outcome == "fit" else "preparation_failed")
        assert p.reason == ("fit_unavailable" if outcome == "fit" else "purchased_overlap")
        assert p.evaluation is None and not p.predictions
        assert value.result.facts.outcome == "failed"
    else:
        assert p.status == "evaluated" and p.evaluation is not None
        assert p.evaluation.status == ("unscorable" if outcome == "unscorable" else "failed")
        assert (p.evaluation.report is not None) == (outcome == "unscorable")
        assert value.result.facts.outcome == ("completed" if outcome == "unscorable" else "failed")
    assert value.measurements.child_cpu_ns > 0
    assert summarize_study(value.ledger).budget.unresolved_attempts == 14


def test_classical_lost_ack_recovers_exact_original_without_rerun(
    tmp_path: Path,
    actual_build: TrustedInstallation,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    f, _, _, candidate = candidate_fixture(tmp_path / "lost-ack", actual_build)
    request = classical_request(f, raw(candidate.receipt), candidate.result)
    close = CandidateStore.close
    raised = False

    def lost_ack(self: CandidateStore) -> None:
        nonlocal raised
        close(self)
        if not raised:
            raised = True
            raise RuntimeError("finite lost acknowledgement after commit")

    with monkeypatch.context() as m:
        m.setattr(CandidateStore, "close", lost_ack)
        with pytest.raises(RuntimeError, match="lost acknowledgement"):
            commit_journal_classical(f.root, request)
    with f.budget.phase():
        with sqlite3.connect(f.root / "candidate.sqlite3") as db:
            receipt = db.execute(
                "SELECT receipt FROM closures WHERE logical_id='classical'"
            ).fetchone()[0]
        result = (f.root / "candidate-output-2").read_bytes()
    monkeypatch.setattr(supervisor, "_run_child", forbidden)
    value = commit_journal_classical(f.root, paid(request))
    assert value.replayed and raw(value.receipt) == receipt and value.result_raw == result
    assert len(value.ledger.records) == 23
    assert summarize_study(value.ledger).budget.unresolved_attempts == 14
