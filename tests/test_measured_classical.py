def test_candidate_with_known_facts_but_unknown_state_is_not_terminal(
    tmp_path: Path,
    actual_build: TrustedInstallation,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    f, _, _, candidate = candidate_fixture(tmp_path / "unknown-parent", actual_build)
    # One explicit test-only corruption transaction, paid by the remaining two
    # setup store attempts. The twelve purchase holds remain unresolved.
    with f.budget.phase(), root_lock(f.root):
        admission = CandidateAdmission.model_validate_json(
            (f.root / "candidate-admission.json").read_bytes()
        )
        meter = Extents(f.root, database_name="candidate.sqlite3")
        store = CandidateStore(
            f.root, admission, (f.root / "candidate-seed.json").read_bytes(), meter
        )
        try:
            before = store.ledger()
            data = json.loads(raw(before))
            data["records"][-1]["event"]["state"] = "unknown"
            after = read_study_ledger(json.dumps(data).encode())
            facts = last_update(after).facts
            assert facts is not None and raw(facts) == raw(candidate.result.facts)
            store.limit_control_growth()
            with store.transaction():
                store.db.execute(
                    "UPDATE state SET ledger=?,revision=?,head=? WHERE id=1",
                    (raw(after), len(after.records), head(after)),
                )
                store.db.execute(
                    "UPDATE records SET digest=? WHERE sequence=?",
                    (message_sha256(after.records[-1]), after.records[-1].sequence),
                )
            assert store.ledger() == after
        finally:
            store.close()
        f.budget.store_attempts += store._transaction_attempts
        assert f.budget.store_attempts == 4
        assert meter.total <= store._transaction_attempts * STORE_ENVELOPE
    request = classical_request(f, raw(candidate.receipt), candidate.result)
    monkeypatch.setattr(supervisor, "_run_child", forbidden)
    with pytest.raises(StudyLedgerError, match="classical_candidate_unknown"):
        commit_journal_classical(f.root, request)
    assert last_update(current(f.root)).state == "unknown"
    assert not (f.root / "candidate-output-2").exists()


